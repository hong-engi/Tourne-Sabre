const mongoose = require( "mongoose" );
const playerSchema = new mongoose.Schema({
    _id:String,
    name:String,
    x:Number,
    y:Number,
    vx:Number,
    vy:Number,
    r:Number,
    sw_angle:Number,
    sw_r:Number,
    sw_w:Number,
    sw_h:Number,
    sw_speed:Number,
    physicsX:{type:Number,default:0},
    physicsY:{type:Number,default:0},
    physicsVx:{type:Number,default:0},
    physicsVy:{type:Number,default:0},
    physicsSeq:{type:Number,default:0},
    intentVx:{type:Number,default:0},
    intentVy:{type:Number,default:0},
    attackMultiplier:{type:Number,default:1},
    augments:{type:[String],default:[]},
    augmentOffer:{type:mongoose.Schema.Types.Mixed,default:null},
    spells:{type:[String],default:['blink','heal']},
    loadout:{type:[String],default:['reverse','giant','accel','thrust']},
    tierPity:{type:mongoose.Schema.Types.Mixed,default:()=>({gold:0,prismatic:0})},
    shield:{type:Number,default:0},
    shieldUntil:{type:Number,default:0},
    invulnerableUntil:{type:Number,default:0},
    reviveUsed:{type:Boolean,default:false},
    choosingAugment:{type:Boolean,default:false},
    skillState:{type:mongoose.Schema.Types.Mixed,default:{}},
    hp:Number,
    hpmax:Number,
    xp:Number,
    lv:Number,
    color:String,
});
const playerModel = mongoose.model("player", playerSchema);

module.exports = playerModel;